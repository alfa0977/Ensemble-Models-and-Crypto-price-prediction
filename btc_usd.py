plot_predictions("Random Forest", rf_pred_tuned)
plot_predictions("AdaBoost", ada_pred_tuned)
plot_predictions("XGBoost", xgb_pred_tuned)
plot_predictions("Stacking", stack_pred_tuned)
plot_predictions("Voting Regressor", vote_pred)


def plot_feature_importance(importance, names, model_name):
    # Convert to list if needed
    if not isinstance(names, list):
        names = names.tolist()

    # Create feature importance pairs
    feature_importance = list(zip(names, importance))
    sorted_feature_importance = sorted(
        feature_importance, key=lambda x: x[1], reverse=True
    )  # Sort by importance
    names_sorted, vals_sorted = zip(*sorted_feature_importance)  # Unpack sorted pairs

    plt.figure(figsize=(12, 6))  # Set figure size
    plt.barh(
        range(len(names_sorted)), vals_sorted, align="center"
    )  # Horizontal bar plot
    plt.yticks(range(len(names_sorted)), names_sorted)  # Set y-tick labels
    plt.title(model_name + " - Feature Importance")  # Title
    plt.xlabel("Importance Value")  # X-axis label
    plt.ylabel("Features")  # Y-axis label
    plt.tight_layout()  # Adjust layout
    plt.show()  # Display plot


plot_feature_importance(
    best_rf.feature_importances_, X_train.columns, "Random Forest"
)  # RF feature importance
plot_feature_importance(
    best_xgb.feature_importances_, X_train.columns, "XGBoost"
)  # XGB feature importance

import numpy as np  # Import numpy
import matplotlib.pyplot as plt  # Import plotting library


def compute_mape(y_true, y_pred):
    # Guard against division by zero errors
    y_true = np.array(y_true).flatten()  # Flatten true values
    y_pred = np.array(y_pred).flatten()  # Flatten predicted values

    # Handle zero values
    valid_indices = y_true != 0  # Indices where true value is not zero
    if valid_indices.any():
        y_true = y_true[valid_indices]  # Filter true values
        y_pred = y_pred[valid_indices]  # Filter predicted values

    # Compute MAPE
    mape = 100 * np.mean(np.abs((y_true - y_pred) / y_true))  # Calculate MAPE
    return mape  # Return MAPE


# Calculate MAPE for each model
mape_rf = compute_mape(y_test, rf_pred_tuned)  # Random Forest MAPE
mape_ada = compute_mape(y_test, ada_pred_tuned)  # AdaBoost MAPE
mape_xgb = compute_mape(y_test, xgb_pred_tuned)  # XGBoost MAPE
mape_stack = compute_mape(y_test, stack_pred_tuned)  # Stacking MAPE
mape_vote = compute_mape(y_test, vote_pred)  # Voting Regressor MAPE

# Visualization
models = [
    "Random Forest",
    "AdaBoost",
    "XGBoost",
    "Stacking",
    "Voting Regressor",
]  # Model names
mape_values = [mape_rf, mape_ada, mape_xgb, mape_stack, mape_vote]  # MAPE values

plt.figure(figsize=(10, 6))  # Set figure size
plt.bar(
    models, mape_values, color=["blue", "green", "red", "purple", "orange"]
)  # Bar plot
plt.ylabel("MAPE (%)")  # Y-axis label
plt.title("Mean Absolute Percentage Error (MAPE) for Different Models")  # Title
plt.xticks(rotation=45)  # Rotate x-tick labels
